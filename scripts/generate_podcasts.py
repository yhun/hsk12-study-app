async def synth_seg(sem: asyncio.Semaphore, voice: str, text: str, path: Path, rate: str = "+0%") -> None:
    if path.exists() and path.stat().st_size > 0:
        return
    async with sem:
        for attempt in range(6):
            try:
                comm = edge_tts.Communicate(text, voice=voice, rate=rate)
                await comm.save(str(path))
                if path.exists() and path.stat().st_size > 0:
                    await asyncio.sleep(0.45)
                    return
            except Exception as exc:
                if attempt == 5:
                    raise RuntimeError(f"Failed synth {path.name} ({voice}): {exc}") from exc
                await asyncio.sleep(3.0 * (attempt + 1))


def make_silence(duration_sec: float, out_path: Path) -> None:
    subprocess.run(
        [
            "ffmpeg",
            "-y",
            "-f",
            "lavfi",
            "-i",
            "anullsrc=r=24000:cl=mono",
            "-t",
            str(duration_sec),
            "-c:a",
            "libmp3lame",
            "-b:a",
            "48k",
            str(out_path),
        ],
        check=True,
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
    )


def get_duration_label(mp3_path: Path) -> str:
    out = subprocess.check_output(
        [
            "ffprobe",
            "-v",
            "error",
            "-show_entries",
            "format=duration",
            "-of",
            "default=noprint_wrappers=1:nokey=1",
            str(mp3_path),
        ],
        text=True,
    ).strip()
    secs = int(round(float(out)))
    return f"{secs // 60}:{secs % 60:02d}"


async def build_episode(ep_id: str, segments: list[tuple[str, str]], pause_short: Path, pause_shadow: Path) -> tuple[str, str, float]:
    out_mp3 = OUT_DIR / f"{ep_id}.mp3"
    if out_mp3.exists() and out_mp3.stat().st_size > 0:
        dur = get_duration_label(out_mp3)
        mb = out_mp3.stat().st_size / (1024 * 1024)
        return (ep_id, dur, mb)

    ep_tmp = TMP_DIR / ep_id
    ep_tmp.mkdir(parents=True, exist_ok=True)
    sem = asyncio.Semaphore(1)

    concat_entries: list[Path] = []
    tasks = []
    for idx, (kind, text) in enumerate(segments, start=1):
        if kind == "pause":
            concat_entries.append(pause_short)
            continue
        if kind == "shadow":
            concat_entries.append(pause_shadow)
            continue

        seg_path = ep_tmp / f"seg_{idx:03d}.mp3"
        concat_entries.append(seg_path)
        if kind == "th":
            tasks.append(synth_seg(sem, TH_VOICE, text, seg_path, rate="+0%"))
        elif kind == "zh":
            tasks.append(synth_seg(sem, ZH_VOICE, text, seg_path, rate="-8%"))
        elif kind == "zh_slow":
            tasks.append(synth_seg(sem, ZH_VOICE, text, seg_path, rate="-22%"))

    await asyncio.gather(*tasks)

    # Normalize each speech segment to 24kHz mono MP3 before concat so stream parameters match identically
    normalized_entries: list[Path] = []
    for idx, src in enumerate(concat_entries, start=1):
        if src in (pause_short, pause_shadow):
            normalized_entries.append(src)
        else:
            norm_path = ep_tmp / f"norm_{idx:03d}.mp3"
            subprocess.run(
                [
                    "ffmpeg",
                    "-y",
                    "-i",
                    str(src),
                    "-ac",
                    "1",
                    "-ar",
                    "24000",
                    "-b:a",
                    "48k",
                    str(norm_path),
                ],
                check=True,
                stdout=subprocess.DEVNULL,
                stderr=subprocess.DEVNULL,
            )
            normalized_entries.append(norm_path)

    concat_txt = ep_tmp / "concat.txt"
    concat_txt.write_text(
        "\n".join(f"file '{p.as_posix()}'" for p in normalized_entries),
        encoding="utf-8",
    )

    out_mp3 = OUT_DIR / f"{ep_id}.mp3"
    subprocess.run(
        [
            "ffmpeg",
            "-y",
            "-f",
            "concat",
            "-safe",
            "0",
            "-i",
            str(concat_txt),
            "-c:a",
            "libmp3lame",
            "-ac",
            "1",
            "-ar",
            "24000",
            "-b:a",
            "48k",
            str(out_mp3),
        ],
        check=True,
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
    )

    dur = get_duration_label(out_mp3)
    mb = out_mp3.stat().st_size / (1024 * 1024)
    return (ep_id, dur, mb)


async def main() -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    TMP_DIR.mkdir(parents=True, exist_ok=True)

    pause_short = TMP_DIR / "pause_short.mp3"
    pause_shadow = TMP_DIR / "pause_shadow.mp3"
    make_silence(0.45, pause_short)
    make_silence(1.25, pause_shadow)

    total_mb = 0.0
    for ep_id, segs in EPISODES.items():
        _, dur, mb = await build_episode(ep_id, segs, pause_short, pause_shadow)
        total_mb += mb
        print(f"{ep_id}.mp3 -> duration {dur}, size {mb:.2f} MB")

    shutil.rmtree(TMP_DIR, ignore_errors=True)
    print(f"All 8 podcast episodes built. Total size: {total_mb:.2f} MB")


if __name__ == "__main__":
    asyncio.run(main())
