import asyncio
import json
import re
import subprocess
from pathlib import Path
import edge_tts

ROOT = Path(__file__).resolve().parent.parent
AUDIO_DIR = ROOT / "public" / "audio"
AUDIO_MAP_FILE = ROOT / "src" / "data" / "audioMap.ts"
VOICE = "zh-CN-XiaoxiaoNeural"


def normalize_key(text: str) -> str:
    return re.sub(r"[（()）\[\]…\s]+", "", text)


def clean_tts_text(text: str) -> str:
    cleaned = text.replace("______", " ")
    cleaned = cleaned.replace("/", "，")
    cleaned = re.sub(r"[（()）\[\]…]+", " ", cleaned)
    cleaned = re.sub(r"\s+", " ", cleaned).strip()
    return cleaned


def extract_all_texts() -> list[tuple[str, str]]:
    """Extract all Chinese texts passed to SpeakButton / speakChinese using esbuild."""
    node_script = r"""
const esbuild = require('esbuild');
const path = require('path');

function loadTs(relPath) {
  const res = esbuild.buildSync({
    entryPoints: [path.resolve(relPath)],
    bundle: true,
    write: false,
    format: 'cjs',
    platform: 'node',
  });
  const code = res.outputFiles[0].text;
  const mod = { exports: {} };
  const fn = new Function('exports', 'require', 'module', code);
  fn(mod.exports, require, mod);
  return mod.exports;
}

const { LESSONS } = loadTs('src/data/lessons.ts');
const { ANTONYMS } = loadTs('src/data/antonyms.ts');
const { RADICALS } = loadTs('src/data/radicals.ts');
const { QUIZZES } = loadTs('src/data/quizzes.ts');
const {
  LISTENING_ITEMS,
  SPEAKING_ITEMS,
  READING_PASSAGES,
  WRITING_CHARS,
  SENTENCE_BUILDERS,
} = loadTs('src/data/skills.ts');

const items = [];

for (const l of LESSONS) {
  for (const ex of l.examples) {
    items.push([ex.zh, ex.zh]);
  }
}

for (const a of ANTONYMS) {
  items.push([a.left.zh, a.left.zh]);
  items.push([a.right.zh, a.right.zh]);
  items.push([`${a.left.zh} ${a.right.zh}`, `${a.left.zh}，${a.right.zh}`]);
}

for (const r of RADICALS) {
  for (const ex of r.examples) {
    items.push([ex.zh, ex.zh]);
  }
}

for (const q of QUIZZES) {
  if (q.zh) {
    const t = q.zh.replace(/______/g, '');
    items.push([t, t]);
  }
}

for (const item of LISTENING_ITEMS) {
  items.push([item.zh, item.zh]);
}

for (const item of SPEAKING_ITEMS) {
  items.push([item.zh, item.zh]);
}

for (const p of READING_PASSAGES) {
  const full = p.lines.map((l) => l.zh).join(' ');
  items.push([full, full]);
  for (const l of p.lines) {
    items.push([l.zh, l.zh]);
  }
}

for (const wc of WRITING_CHARS) {
  items.push([wc.char, wc.char]);
}

for (const sb of SENTENCE_BUILDERS) {
  const full = sb.tokens.join('');
  items.push([full, full]);
}

console.log(JSON.stringify(items));
"""
    raw = subprocess.check_output(
        ["node", "-e", node_script],
        cwd=str(ROOT),
        text=True,
        encoding="utf-8",
    )
    pairs: list[list[str]] = json.loads(raw)

    # Deduplicate by normalized key while keeping deterministic order
    seen: dict[str, str] = {}
    for orig, tts in pairs:
        key = normalize_key(orig)
        tts_clean = clean_tts_text(tts)
        if key and tts_clean and key not in seen:
            seen[key] = tts_clean
    return list(seen.items())


async def synth_one(
    sem: asyncio.Semaphore,
    key: str,
    tts_text: str,
    filename: str,
) -> tuple[str, str, bool]:
    out_path = AUDIO_DIR / filename
    if out_path.exists() and out_path.stat().st_size > 0:
        return (key, filename, True)

    async with sem:
        for attempt in range(3):
            try:
                comm = edge_tts.Communicate(tts_text, voice=VOICE)
                await comm.save(str(out_path))
                if out_path.exists() and out_path.stat().st_size > 0:
                    return (key, filename, True)
            except Exception as exc:
                if attempt == 2:
                    print(f"FAILED {filename} ({key}): {exc}")
                await asyncio.sleep(1.0 + attempt)
    return (key, filename, False)


async def main() -> None:
    AUDIO_DIR.mkdir(parents=True, exist_ok=True)
    entries = extract_all_texts()
    print(f"Unique Chinese audio entries to process: {len(entries)}")

    sem = asyncio.Semaphore(8)
    tasks = []
    for idx, (key, tts_text) in enumerate(entries, start=1):
        filename = f"a{idx:04d}.mp3"
        tasks.append(synth_one(sem, key, tts_text, filename))

    results = await asyncio.gather(*tasks)

    mapping: dict[str, str] = {}
    failed = 0
    for key, filename, ok in results:
        if ok:
            mapping[key] = filename
        else:
            failed += 1

    lines = [
        "// Auto-generated by scripts/generate_audio.py using edge-tts (zh-CN-XiaoxiaoNeural)",
        "export const AUDIO_MAP: Record<string, string> = {",
    ]
    for key, filename in mapping.items():
        lines.append(f"  {json.dumps(key, ensure_ascii=False)}: {json.dumps(filename)},")
    lines.append("};")
    lines.append("")

    AUDIO_MAP_FILE.write_text("\n".join(lines), encoding="utf-8")

    total_bytes = sum(f.stat().st_size for f in AUDIO_DIR.glob("*.mp3"))
    print(f"Generated/verified: {len(mapping)} MP3 files, failed: {failed}")
    print(f"Total audio size: {total_bytes / (1024 * 1024):.2f} MB")


if __name__ == "__main__":
    asyncio.run(main())
